import { z } from "zod";

const isProd = process.env.NODE_ENV === "production";
const DEV_JWT_FALLBACK = "local-development-jwt-secret";

const envSchema = z.object({
  QRS_ARTICLES_PUBLISH_TOKEN: z.string().optional(),
  YANDEX_SAFE_BROWSING_API_KEY: z.string().optional(),
  GOOGLE_WEB_RISK_API_KEY: z.string().optional(),
  GOOGLE_WEB_RISK_ENABLED: z.enum(["true", "false"]).default("false").transform(v => v === "true"),
  ABUSE_CHECK_ENABLED: z.enum(["true", "false"]).default("true").transform(v => v === "true"),
  ABUSE_REQUIRE_VERIFIED_EMAIL: z.enum(["true", "false"]).default("false").transform(v => v === "true"),
  ABUSE_CHECK_TIMEOUT_MS: z.coerce.number().int().min(1).default(3000),
  ABUSE_REPORTS_THRESHOLD: z.coerce.number().int().min(1).default(3),
  ABUSE_RECHECK_HOUR: z.coerce.number().int().min(0).max(23).default(4),
  ABUSE_RECHECK_BATCH_DELAY_MS: z.coerce.number().int().min(1).default(1000),
  ABUSE_SB_DAILY_QUOTA: z.coerce.number().int().min(1).default(9000),
  ABUSE_AUDIT_IP_RETENTION_DAYS: z.coerce.number().int().min(1).default(365),
  ABUSE_NEW_ACCOUNT_HOURS: z.coerce.number().int().min(1).default(24),
  QR_CREATE_PER_HOUR: z.coerce.number().int().min(1).default(30),
  QR_CREATE_PER_IP_PER_HOUR: z.coerce.number().int().min(1).default(60),
  QR_URL_CHANGE_PER_HOUR: z.coerce.number().int().min(1).default(10),
  QR_URL_CHANGE_USER_PER_HOUR: z.coerce.number().int().min(1).default(60),
  ABUSE_REPORTS_PER_IP_PER_HOUR: z.coerce.number().int().min(1).default(5),
  REGISTER_PER_IP_PER_DAY: z.coerce.number().int().min(1).default(10),
  DATABASE_URL: z.string().min(1).default("postgresql://postgres:postgres@localhost:5432/qr_saas?schema=public"),
  JWT_SECRET: isProd
    ? z
        .string()
        .min(32, "JWT_SECRET must be at least 32 characters in production")
        .refine((value) => value !== DEV_JWT_FALLBACK, "JWT_SECRET must not use the development default")
    : z.string().min(16).default(DEV_JWT_FALLBACK),
  APP_URL: z.string().url().default(isProd ? "https://qr-s.ru" : "http://localhost:3000"),
  JWT_PREVIOUS_SECRET: z.string().min(16).optional(),
  JWT_ROTATED_AT: z.string().datetime({ offset: true }).optional(),
  REDIS_URL: z.string().url().optional(),
  SMTP_HOST: z.string().optional(),
  SMTP_PORT: z.coerce.number().int().min(1).max(65535).default(465),
  SMTP_USER: z.string().optional(),
  SMTP_PASS: z.string().optional(),
  SMTP_FROM: z.string().optional(),
  ADMIN_INTEGRATIONS_KEY: z.string().optional(),
  TELEGRAM_BOT_TOKEN: z.string().optional(),
  METRIKA_OAUTH_TOKEN: z.string().optional(),
  YANDEX_CLIENT_ID: z.string().optional(),
  YANDEX_CLIENT_SECRET: z.string().optional(),
  YANDEX_REDIRECT_URI: z.string().url().optional(),
  YANDEX_AUTH_ENABLED: z.enum(["true", "false"]).default("true").transform(value => value === "true"),
  BILLING_PROVIDER: z.enum(["yookassa", "robokassa"]).default("yookassa"),
  ROBOKASSA_MERCHANT_LOGIN: z.string().optional(),
  ROBOKASSA_PASSWORD1: z.string().optional(),
  ROBOKASSA_PASSWORD2: z.string().optional(),
  ROBOKASSA_TEST_PASSWORD1: z.string().optional(),
  ROBOKASSA_TEST_PASSWORD2: z.string().optional(),
  ROBOKASSA_TEST_MODE: z.enum(["true", "false"]).default("true").transform(value => value === "true"),
  ROBOKASSA_HASH_ALGORITHM: z.enum(["MD5", "SHA256", "SHA512"]).default("SHA256"),
}).refine(value => Boolean(value.JWT_PREVIOUS_SECRET) === Boolean(value.JWT_ROTATED_AT), {
  message: "JWT_PREVIOUS_SECRET and JWT_ROTATED_AT must be configured together",
});

export const env = envSchema.parse({
  ...process.env,
  DATABASE_URL: process.env.DATABASE_URL,
  JWT_SECRET: process.env.JWT_SECRET,
  JWT_PREVIOUS_SECRET: process.env.JWT_PREVIOUS_SECRET || undefined,
  JWT_ROTATED_AT: process.env.JWT_ROTATED_AT || undefined,
  APP_URL: process.env.APP_URL ?? (isProd ? "https://qr-s.ru" : "http://localhost:3000"),
  REDIS_URL: process.env.REDIS_URL,
  SMTP_HOST: process.env.SMTP_HOST || undefined,
  SMTP_PORT: process.env.SMTP_PORT || undefined,
  SMTP_USER: process.env.SMTP_USER || undefined,
  SMTP_PASS: process.env.SMTP_PASS || undefined,
  SMTP_FROM: process.env.SMTP_FROM || undefined,
  ADMIN_INTEGRATIONS_KEY: process.env.ADMIN_INTEGRATIONS_KEY,
  TELEGRAM_BOT_TOKEN: process.env.TELEGRAM_BOT_TOKEN,
  METRIKA_OAUTH_TOKEN: process.env.METRIKA_OAUTH_TOKEN,
  YANDEX_CLIENT_ID: process.env.YANDEX_CLIENT_ID,
  YANDEX_CLIENT_SECRET: process.env.YANDEX_CLIENT_SECRET,
  YANDEX_REDIRECT_URI: process.env.YANDEX_REDIRECT_URI || undefined,
  YANDEX_AUTH_ENABLED: process.env.YANDEX_AUTH_ENABLED || undefined,
  BILLING_PROVIDER: process.env.BILLING_PROVIDER,
  ROBOKASSA_MERCHANT_LOGIN: process.env.ROBOKASSA_MERCHANT_LOGIN,
  ROBOKASSA_PASSWORD1: process.env.ROBOKASSA_PASSWORD1,
  ROBOKASSA_PASSWORD2: process.env.ROBOKASSA_PASSWORD2,
  ROBOKASSA_TEST_PASSWORD1: process.env.ROBOKASSA_TEST_PASSWORD1,
  ROBOKASSA_TEST_PASSWORD2: process.env.ROBOKASSA_TEST_PASSWORD2,
  ROBOKASSA_TEST_MODE: process.env.ROBOKASSA_TEST_MODE,
  ROBOKASSA_HASH_ALGORITHM: process.env.ROBOKASSA_HASH_ALGORITHM,
});
